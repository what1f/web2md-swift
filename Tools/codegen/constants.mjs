// Generates Sources/Web2MD/Generic/Constants.swift from upstream defuddle.
// Usage: node constants.mjs <defuddle-dir> > Constants.swift
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const dir = process.argv[2];
const c = await import(pathToFileURL(path.join(dir, 'dist/constants.js')).href);

const lit = (s) => {
  let out = '"';
  for (const ch of String(s)) {
    const code = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return out + '"';
};
const arr = (a) => '[\n' + [...a].map(x => '        ' + lit(x) + ',').join('\n') + '\n    ]';
const lines = [];
lines.push('// Generated by Tools/codegen/constants.mjs from defuddle src/constants.ts. Do not edit.');
lines.push('// Copyright (c) 2025 Steph Ango (@kepano), MIT License.');
lines.push('');
lines.push('enum Constants {');
const emitList = (name, v) => lines.push(`    static let ${name}: [String] = ${arr(v)}`);
const emitSet = (name, v) => lines.push(`    static let ${name}: Set<String> = ${arr(v)}`);
const emitStr = (name, v) => lines.push(`    static let ${name} = ${lit(v)}`);
emitList('entryPointElements', c.ENTRY_POINT_ELEMENTS);
lines.push(`    static let mobileWidth = ${c.MOBILE_WIDTH}`);
emitList('blockElements', c.BLOCK_ELEMENTS);
emitStr('blockElementsSelector', c.BLOCK_ELEMENTS_SELECTOR);
emitSet('blockElementsSet', c.BLOCK_ELEMENTS_SET);
emitSet('blockLevelElements', c.BLOCK_LEVEL_ELEMENTS);
emitSet('preserveElements', c.PRESERVE_ELEMENTS);
emitSet('inlineElements', c.INLINE_ELEMENTS);
emitStr('contentElementSelector', c.CONTENT_ELEMENT_SELECTOR);
emitStr('hiddenExactSelector', c.HIDDEN_EXACT_SELECTOR);
emitStr('hiddenExactSkipSelector', c.HIDDEN_EXACT_SKIP_SELECTOR);
emitList('exactSelectors', c.EXACT_SELECTORS);
emitStr('exactSelectorsJoined', c.EXACT_SELECTORS_JOINED);
emitList('testAttributes', c.TEST_ATTRIBUTES);
emitList('partialSelectors', c.PARTIAL_SELECTORS);
emitStr('partialSelectorsPattern', c.PARTIAL_SELECTORS_REGEX.source);
emitStr('partialSelectorsAnchoredPattern', c.PARTIAL_SELECTORS_ANCHORED_REGEX.source);
emitStr('testAttributesSelector', c.TEST_ATTRIBUTES_SELECTOR);
emitStr('footnoteInlineReferences', c.FOOTNOTE_INLINE_REFERENCES);
emitStr('footnoteListSelectors', c.FOOTNOTE_LIST_SELECTORS);
emitSet('allowedEmptyElements', c.ALLOWED_EMPTY_ELEMENTS);
emitSet('allowedAttributes', c.ALLOWED_ATTRIBUTES);
emitSet('allowedAttributesDebug', c.ALLOWED_ATTRIBUTES_DEBUG);
lines.push('    static let tailwindColors: [String: [String: String]] = [');
for (const [k, v] of Object.entries(c.TAILWIND_COLORS)) {
  lines.push(`        ${lit(k)}: [` + Object.entries(v).map(([a, b]) => `${lit(a)}: ${lit(b)}`).join(', ') + '],');
}
lines.push('    ]');
lines.push('    static let tailwindSpecial: [String: String] = [' + Object.entries(c.TAILWIND_SPECIAL).map(([a, b]) => `${lit(a)}: ${lit(b)}`).join(', ') + ']');
emitStr('twColorClassPattern', c.TW_COLOR_CLASS_RE.source);
emitStr('twSpecialClassPattern', c.TW_SPECIAL_CLASS_RE.source);
emitStr('twArbitraryPattern', c.TW_ARBITRARY_RE.source);
const known = new Set(['ENTRY_POINT_ELEMENTS','MOBILE_WIDTH','BLOCK_ELEMENTS','BLOCK_ELEMENTS_SELECTOR','BLOCK_ELEMENTS_SET','BLOCK_LEVEL_ELEMENTS','PRESERVE_ELEMENTS','INLINE_ELEMENTS','CONTENT_ELEMENT_SELECTOR','HIDDEN_EXACT_SELECTOR','HIDDEN_EXACT_SKIP_SELECTOR','EXACT_SELECTORS','EXACT_SELECTORS_JOINED','TEST_ATTRIBUTES','PARTIAL_SELECTORS','PARTIAL_SELECTORS_REGEX','PARTIAL_SELECTORS_ANCHORED_REGEX','TEST_ATTRIBUTES_SELECTOR','FOOTNOTE_INLINE_REFERENCES','FOOTNOTE_LIST_SELECTORS','ALLOWED_EMPTY_ELEMENTS','ALLOWED_ATTRIBUTES','ALLOWED_ATTRIBUTES_DEBUG','TAILWIND_COLORS','TAILWIND_SPECIAL','TW_COLOR_CLASS_RE','TW_SPECIAL_CLASS_RE','TW_ARBITRARY_RE']);
const missing = Object.keys(c).filter(k => !known.has(k));
if (missing.length) console.error('Unhandled exports:', missing.join(', '));
lines.push('}');
console.log(lines.join('\n'));
